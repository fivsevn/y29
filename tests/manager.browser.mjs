// Optional isolated browser checks; writes only temporary copied data and an external temporary profile folder.
import { mkdtemp,cp,mkdir,readFile,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { createPreviewServer } from '../serve.js';
import { fileURLToPath } from 'node:url';
const { chromium } = await import(process.env.Y29_PLAYWRIGHT_MODULE || 'playwright');
const repo=fileURLToPath(new URL('../',import.meta.url));
const temp=await mkdtemp(join(tmpdir(),'lucifer-manager-browser-'));
const root=join(temp,'project');await mkdir(root);
await cp(join(repo,'lucifer0'),join(root,'lucifer0'),{recursive:true});
await mkdir(join(root,'assets'));await cp(join(repo,'assets/fonts'),join(root,'assets/fonts'),{recursive:true});
const privateDir=join(temp,'profiles');
const server=createPreviewServer({root,managementRoot:join(root,'lucifer0'),privateDirectory:privateDir});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844}});const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const shots=process.env.Y29_SCREENSHOTS || join(tmpdir(),'y29-manager-browser');await mkdir(shots,{recursive:true});
let checks=0;const check=(v,m)=>{assert.ok(v,m);checks++;};
try {
 await page.goto(base+'/lucifer0/manage/');await page.locator('.user-row').first().waitFor();
 const startCount=await page.locator('.user-row').count();check(startCount>=50,'at least50 initial users');
 await page.screenshot({path:join(shots,'phone-users.png')});
 await page.getByLabel('搜索用户档案').fill('黎星');check(await page.locator('.user-row').count()===1,'name search');
 await page.getByLabel('搜索用户档案').fill('');
 await page.getByLabel('作品来源',{exact:true}).selectOption('真心猎手');check(await page.locator('.user-row').count()===8,'work filter');
 await page.getByLabel('作品来源',{exact:true}).selectOption('all');
 await page.getByRole('link',{name:'＋ 新建用户'}).click();await page.locator('.record-form').waitFor();
 check(await page.getByRole('switch').count()===5,'five independent switches');
 await page.getByLabel('昵称',{exact:true}).fill('路西法ξ测试');
 await page.locator('[name="id"]').fill('browser-check');await page.locator('[name="handle"]').fill('browser_check');
 await page.locator('[name="sourceWork"]').fill('另一部作品');
 await page.locator('[name="inFollowing"]').check();await page.locator('[name="allowPosts"]').uncheck();
 await page.locator('[name="notes"]').fill('synthetic private marker — browser only');
 await page.locator('[name="tags"]').fill('夜猫子\n唱片\n浏览器测试标签');
 await page.locator('[name="occupation"]').fill('唱片店店员');
 await page.locator('[name="gender"]').fill('自行设定');
 await page.locator('[name="activeHours"]').fill('21:00–23:00');
 await page.locator('summary').filter({hasText:'表达与知情范围'}).click();
 await page.locator('[name="currentStatus"]').fill('整理新唱片');
 await page.locator('[name="topics"]').fill('音乐\n天气');await page.locator('[name="voiceExamples"]').fill('今天这张唱片值得再听一次。');
 await page.getByRole('button',{name:'创建用户',exact:true}).click();
 await page.getByText('档案已保存，下次读取即使用新设定。',{exact:true}).waitFor();
 check(page.url().endsWith('#/user/browser-check'),'create selects savedrecord');
 const registry=JSON.parse(await readFile(join(root,'lucifer0/users/registry.json'),'utf8'));
 const added=registry.users.find(u=>u.id==='browser-check');check(added.inFollowing&&added.sourceWork==='另一部作品'&&!added.allowPosts&&added.allowReplies,'independent public controls persisted');
 const profile=JSON.parse(await readFile(join(privateDir,'browser-check.json'),'utf8'));
 check(profile.notes.includes('synthetic private marker')&&profile.tags.includes('唱片')&&profile.currentStatus==='整理新唱片'&&profile.basics.activeHours==='21:00–23:00','private details persisted externally');
 check(!(await readFile(join(root,'lucifer0/users/registry.json'),'utf8')).includes('synthetic private marker'),'private notes excluded registry');
 check(!(await readFile(join(root,'lucifer0/data/feed.json'),'utf8')).includes('synthetic private marker'),'private notes excluded feed');
 await page.reload();await page.locator('[name="notes"]').waitFor();check((await page.locator('[name="notes"]').inputValue()).includes('synthetic private marker'),'reload reads savedprofile');
 await page.locator('[name="enabled"]').uncheck();await page.getByRole('button',{name:'保存档案',exact:true}).click();await page.locator('#save-user').filter({hasText:'保存档案'}).waitFor();
 check(!(await page.locator('[name="enabled"]').isChecked()),'pause persists');
 await page.locator('[name="sourceWork"]').fill('');
 await page.getByRole('button',{name:'保存档案',exact:true}).click();await page.locator('#save-user').filter({hasText:'保存档案'}).waitFor();
 const independent=JSON.parse(await readFile(join(root,'lucifer0/users/registry.json'),'utf8')).users.find(u=>u.id==='browser-check');
 check(independent.sourceWork===''&&independent.inFollowing===true,'following membership remains independent of source work');
 await page.getByRole('link',{name:'← 用户档案',exact:true}).click();await page.getByRole('heading',{name:'用户档案',exact:true}).waitFor();
 await page.getByLabel('用户标签',{exact:true}).selectOption('浏览器测试标签');check(await page.locator('.user-row').count()===1,'tag filter finds edited profile');
 await page.getByLabel('用户标签',{exact:true}).selectOption('all');
 await page.getByRole('link',{name:'抽选预览 ↗'}).click();await page.getByRole('button',{name:'随机抽选',exact:true}).click();
 await page.getByRole('heading',{name:'本轮 5 位用户'}).waitFor();check(await page.locator('#draw-results .user-row').count()===5,'draw gets five users');check(await page.locator('#draw-results').getByText('路西法ξ测试',{exact:true}).count()===0,'draw omits disabled');
 await page.locator('#notice.visible').waitFor({state:'hidden'});await page.screenshot({path:join(shots,'phone-draw.png')});
 await page.goto(base+'/lucifer0/manage/#/user/browser-check');await page.locator('#delete-user').waitFor();page.once('dialog',d=>d.accept());await page.locator('#delete-user').click();await page.getByRole('heading',{name:'用户档案',exact:true}).waitFor();check(await page.locator('.user-row').count()===startCount,'delete restores list count');
 await page.goto(base+'/lucifer0/manage/#/user/lixing');await page.locator('#delete-user').waitFor();check(await page.locator('#delete-user').isDisabled(),'historical account deleteblocked');
 await page.locator('#notice.visible').waitFor({state:'hidden'});await page.screenshot({path:join(shots,'phone-editor.png')});
 for(const width of [320,390,768,1440]){await page.setViewportSize({width,height:844});check(await page.evaluate(()=>document.documentElement.scrollWidth===document.documentElement.clientWidth&&document.querySelector('.manager-shell').getBoundingClientRect().width<=480),'phone only width'+width);}
 check(errors.length===0,'no pageerrors '+errors.join(','));
 console.log(JSON.stringify({checks,users:startCount,screenshots:shots}));
} finally {await browser.close();await new Promise(resolve=>server.close(resolve));await rm(temp,{recursive:true,force:true});}
